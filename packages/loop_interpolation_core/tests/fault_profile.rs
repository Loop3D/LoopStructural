#[test]
fn displacement_matches_python() {
    let smooth = settings(Extension::Smooth);
    for &(d3, side, gx, gy, gz, v) in CASES {
        let p = profile(d3);
        if side == 0 {
            close(p.eval(gx, gy, gz), v);
        } else {
            let s = if side > 0 { 1.0 } else { -1.0 };
            let forced = s * gx.abs().max(1e-9);
            let side = if side > 0 { Side::Hanging } else { Side::Foot };
            close(p.block_displacement(gx, forced, gy, gz, side, &smooth), v);
        }
    }
}

#[test]
fn mirror_and_free_use_the_forced_value() {
    let p = profile(true);
    let mirror = settings(Extension::Mirror);
    let smooth = settings(Extension::Smooth);
    close(
        p.block_displacement(-0.3, 0.3, 0.3, 0.3, Side::Hanging, &mirror),
        p.eval(0.3, 0.3, 0.3),
    );
    close(
        p.block_displacement(-0.3, 0.3, 0.3, 0.3, Side::Free, &smooth),
        p.eval(0.3, 0.3, 0.3),
    );
    close(
        p.block_displacement(-0.3, 0.3, 0.3, 0.3, Side::Absent, &smooth),
        p.eval(0.3, 0.3, 0.3),
    );
}
