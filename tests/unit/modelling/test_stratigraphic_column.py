class TestStratigraphicUnit:
    def test_construction_with_explicit_id(self):
        unit = StratigraphicUnit(name="A", thickness=10, id=0)
        assert unit.name == "A"
        assert unit.thickness == 10
        assert unit.id == 0
        assert unit.element_type == StratigraphicColumnElementType.UNIT
        assert unit.data is None

    def test_default_colour_is_random_rgb_triplet(self):
        unit = StratigraphicUnit(name="A", id=0)
        colour = np.asarray(unit.colour)
        assert colour.shape == (3,)
        assert np.all(colour >= 0) and np.all(colour <= 1)

    def test_explicit_colour_preserved(self):
        unit = StratigraphicUnit(name="A", id=0, colour="red")
        assert unit.colour == "red"

    def test_thickness_setter_updates_value(self):
        unit = StratigraphicUnit(name="A", id=0, thickness=5)
        unit.thickness = 15
        assert unit.thickness == 15

    def test_id_setter_rejects_non_integer(self):
        unit = StratigraphicUnit(name="A", id=0)
        with pytest.raises(TypeError):
            unit.id = "not-an-int"

    def test_id_setter_rejects_float(self):
        unit = StratigraphicUnit(name="A", id=0)
        with pytest.raises(TypeError):
            unit.id = 1.5

    def test_min_max_default_when_unset(self):
        unit = StratigraphicUnit(name="A", id=0)
        assert unit.min() == 0
        assert unit.max() == np.inf

    def test_min_max_reflect_assigned_values(self):
        unit = StratigraphicUnit(name="A", id=0)
        unit.min_value = 1.0
        unit.max_value = 2.0
        assert unit.min() == 1.0
        assert unit.max() == 2.0

    def test_to_dict_converts_ndarray_colour_to_list(self):
        unit = StratigraphicUnit(name="A", id=0, thickness=5, colour=np.array([0.1, 0.2, 0.3]))
        d = unit.to_dict()
        assert d["name"] == "A"
        assert d["thickness"] == 5
        assert d["id"] == 0
        assert isinstance(d["colour"], list)
        assert d["colour"] == pytest.approx([0.1, 0.2, 0.3])

    def test_to_dict_preserves_string_colour(self):
        unit = StratigraphicUnit(name="A", id=0, colour="grey")
        d = unit.to_dict()
        assert d["colour"] == "grey"

    def test_from_dict_roundtrip(self):
        original = StratigraphicUnit(name="A", id=3, thickness=7, colour="blue")
        d = original.to_dict()
        restored = StratigraphicUnit.from_dict(d)
        assert restored.name == original.name
        assert restored.thickness == original.thickness
        assert restored.id == original.id
        assert restored.colour == original.colour
        assert restored.uuid == original.uuid

    def test_from_dict_requires_dict(self):
        with pytest.raises(TypeError):
            StratigraphicUnit.from_dict("not-a-dict")

    def test_str_contains_name_colour_thickness(self):
        unit = StratigraphicUnit(name="A", id=0, thickness=5, colour="grey")
        s = str(unit)
        assert "A" in s
        assert "grey" in s
        assert "5" in s

    def test_from_dict_without_id_raises_type_error_bug(self):
        """Documents a bug: StratigraphicUnit.from_dict() (and StratigraphicUnit()
        construction in general) is documented as accepting ``id=None`` by default,
        but the ``id`` property setter unconditionally requires an int:

            if not isinstance(value, int):
                raise TypeError("ID must be an integer")

        Since ``__init__`` always does ``self.id = id`` (even when id is the
        default None), any code path that omits "id" - such as
        StratigraphicUnit.from_dict() being fed a dict without an "id" key, which
        is exactly the shape produced by hand-written/legacy stratigraphic column
        dicts - raises TypeError instead of constructing a unit with some sentinel
        id. This test documents the CURRENT (broken) behaviour.
        """
        with pytest.raises(TypeError):
            StratigraphicUnit.from_dict({"name": "A", "thickness": 5})

    def test_construction_without_id_raises_type_error_bug(self):
        """Same root cause as test_from_dict_without_id_raises_type_error_bug:
        omitting `id` (its documented default) at construction time raises
        TypeError rather than succeeding with an unset/sentinel id.
        """
        with pytest.raises(TypeError):
            StratigraphicUnit(name="A")


