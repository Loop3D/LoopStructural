class TestGroupsAndSummaries:
    def _build_two_group_column(self):
        column = StratigraphicColumn()
        column.clear(basement=False)
        column.add_unit("A", thickness=10, id=0)
        column.add_unconformity("unc1")
        column.add_unit("B", thickness=5, id=1)
        return column

    def test_get_groups_splits_on_unconformities(self):
        column = self._build_two_group_column()
        groups = column.get_groups()
        assert len(groups) == 2
        # get_groups walks self.order in reverse, so the last-added unit
        # ("B", above the unconformity) forms the first (youngest) group.
        assert [u.name for u in groups[0].units] == ["B"]
        assert [u.name for u in groups[1].units] == ["A"]

    def test_get_groups_default_names(self):
        column = self._build_two_group_column()
        groups = column.get_groups()
        assert groups[0].name == "Group_0"
        assert groups[1].name == "Group_1"

    def test_get_groups_uses_group_mapping_overrides(self):
        column = self._build_two_group_column()
        column.group_mapping = {"Group_0": "Upper", "Group_1": "Lower"}
        groups = column.get_groups()
        assert groups[0].name == "Upper"
        assert groups[1].name == "Lower"

    def test_get_group_for_unit_name(self):
        column = self._build_two_group_column()
        group = column.get_group_for_unit_name("A")
        assert group is not None
        assert any(u.name == "A" for u in group.units)

    def test_get_group_for_unit_name_missing_returns_none(self):
        column = self._build_two_group_column()
        assert column.get_group_for_unit_name("missing") is None

    def test_get_unitname_groups(self):
        column = self._build_two_group_column()
        assert column.get_unitname_groups() == [["B"], ["A"]]

    def test_get_group_unit_pairs(self):
        column = self._build_two_group_column()
        pairs = column.get_group_unit_pairs()
        assert pairs == [("Group_0", "B"), ("Group_1", "A")]

    def test_get_isovalues(self):
        column = self._build_two_group_column()
        isovalues = column.get_isovalues()
        assert set(isovalues.keys()) == {"A", "B"}
        assert isovalues["A"]["value"] == 0
        assert isovalues["A"]["group"] == "Group_1"
        assert isovalues["B"]["value"] == 0
        assert isovalues["B"]["group"] == "Group_0"

    def test_get_isovalues_multi_unit_group(self):
        # Isovalues must match update_unit_values: the base of the oldest
        # unit in a group is 0, and each unit's thickness gives the base
        # value of the next (younger) unit.
        column = StratigraphicColumn()
        column.clear(basement=False)
        column.add_unit("A", thickness=10, id=0)
        column.add_unit("B", thickness=5, id=1)
        column.add_unit("C", thickness=3, id=2)
        isovalues = column.get_isovalues()
        assert isovalues["A"]["value"] == 0
        assert isovalues["B"]["value"] == 10
        assert isovalues["C"]["value"] == 15

    def test_get_isovalues_where_top_returns_unit_top(self):
        # where='top' must give each unit's top, i.e. base + thickness --
        # the same value that where='bottom' (default) gives the next
        # (younger) unit as its base.
        column = StratigraphicColumn()
        column.clear(basement=False)
        column.add_unit("A", thickness=10, id=0)
        column.add_unit("B", thickness=5, id=1)
        column.add_unit("C", thickness=3, id=2)
        isovalues = column.get_isovalues(where='top')
        assert isovalues["A"]["value"] == 10
        assert isovalues["B"]["value"] == 15
        assert isovalues["C"]["value"] == 18

    def test_get_isovalues_invalid_where_raises(self):
        column = self._build_two_group_column()
        with pytest.raises(ValueError):
            column.get_isovalues(where="middle")


